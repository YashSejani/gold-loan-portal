import { LeadRequestSchema, maskMobile, zodToFields, type Channel, type LeadDto } from '@goldloan/shared';
import type { Lead, LoanScheme } from '@prisma/client';
import { z } from 'zod';
import { prisma } from '../db';
import { ConflictError, InternalError, ValidationError } from '../lib/errors';
import { bpsToRatio, mgToGrams, paiseToRupees, parseDecimalToMg } from '../lib/money';
import * as quoteService from './quoteService';
import { getActiveById } from './schemeService';

const DUPLICATE_WINDOW_MS = 7 * 24 * 60 * 60 * 1000;

type LeadWithPlan = Lead & { plan: LoanScheme };

/** The only lead → response mapper. The raw mobile never leaves this service. */
export function toLeadDto(lead: LeadWithPlan): LeadDto {
  return {
    applicationId: lead.applicationId,
    status: lead.status,
    createdAt: lead.createdAt.toISOString(),
    fullName: lead.fullName,
    mobileNumber: maskMobile(lead.mobileNumber),
    netWeightGrams: mgToGrams(BigInt(lead.netWeightMg)),
    grossWeightGrams: mgToGrams(BigInt(lead.grossWeightMg)),
    karat: lead.karat,
    planId: lead.planId,
    planName: lead.plan.name,
    pureGoldGrams: mgToGrams(BigInt(lead.pureGoldMg.toFixed(0))),
    goldValueRupees: paiseToRupees(lead.goldValuePaise),
    appliedLtv: bpsToRatio(lead.appliedLtvBps),
    eligibleLoan: lead.eligibleLoanRupees,
  };
}

/**
 * The ONLY way a lead is created (form route and agent confirm). Order per CLAUDE.md §4.4:
 * validate → plan active → 7-day duplicate → server-side recalculation → insert.
 * Any failure before the insert writes nothing.
 */
export async function create(rawInput: unknown, options: { channel?: Channel } = {}): Promise<LeadDto> {
  // 1. Validate (strips unknown keys, so client money fields never get past here)
  const parsed = LeadRequestSchema.safeParse(rawInput);
  if (!parsed.success) throw new ValidationError(zodToFields(parsed.error));
  const input = parsed.data;

  // 2. Plan exists and is active → else 404 PLAN_NOT_FOUND
  await getActiveById(input.planId);

  // 3. Same mobile within the last 7 days (rolling, any status) → 409
  const existing = await prisma.lead.findFirst({
    where: { mobileNumber: input.mobileNumber, createdAt: { gte: new Date(Date.now() - DUPLICATE_WINDOW_MS) } },
    orderBy: { createdAt: 'desc' },
    select: { applicationId: true, createdAt: true },
  });
  if (existing) {
    throw new ConflictError(
      'DUPLICATE_APPLICATION',
      'An application from this mobile number was already submitted in the last 7 days.',
      [{ field: 'mobileNumber', message: 'Already applied in the last 7 days' }],
      { existingApplicationId: existing.applicationId, existingSubmittedAt: existing.createdAt.toISOString() },
    );
  }

  // 4. Recompute with the same function as POST /quotes, current rate, plan LTV from the DB
  const quote = await quoteService.calculate(
    { netWeightGrams: input.netWeightGrams, grossWeightGrams: input.grossWeightGrams, karat: input.karat },
    { planId: input.planId },
  );
  const planQuote = quote.plans[0];
  if (!planQuote) throw new InternalError();

  // 5. Insert with snapshots (applicationId is generated by Postgres as 'GL-' || id)
  const lead = await prisma.lead.create({
    data: {
      fullName: input.fullName,
      mobileNumber: input.mobileNumber,
      grossWeightMg: Number(parseDecimalToMg(input.grossWeightGrams)),
      netWeightMg: Number(parseDecimalToMg(input.netWeightGrams)),
      karat: input.karat,
      planId: planQuote.plan.id,
      rate24kPaisePerGram: Number(quote.ratePaisePerGram),
      appliedLtvBps: planQuote.appliedLtvBps,
      pureGoldMg: quote.pureGoldMg.toString(),
      goldValuePaise: quote.goldValuePaise,
      eligibleLoanRupees: planQuote.eligibleLoanRupees,
      status: 'SUBMITTED',
      channel: options.channel ?? input.channel,
    },
    include: { plan: true },
  });
  return toLeadDto(lead);
}

const ListLeadsQuerySchema = z.object({
  // "?planId=" (e.g. an "All plans" option) means no filter
  planId: z
    .string({ error: 'planId must be a single value' })
    .trim()
    .optional()
    .transform((value) => value || undefined),
});

/** Stored snapshots only (never recalculated), newest first, masked mobiles. */
export async function list(rawQuery: unknown): Promise<{ data: LeadDto[]; meta: { total: number } }> {
  const parsed = ListLeadsQuerySchema.safeParse(rawQuery ?? {});
  if (!parsed.success) throw new ValidationError(zodToFields(parsed.error));

  const leads = await prisma.lead.findMany({
    where: parsed.data.planId ? { planId: parsed.data.planId } : {},
    orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
    include: { plan: true },
  });
  return { data: leads.map(toLeadDto), meta: { total: leads.length } };
}
